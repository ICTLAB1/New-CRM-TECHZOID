/**
 * Trim, downscale and base64 the supplied brand assets into a TypeScript
 * module the PDF renderer can embed.
 *
 * jsPDF needs actual image bytes, and these are seed values for the settings
 * record (the app stores uploaded logos the same way), so they ship as data
 * URIs rather than as files fetched at render time.
 *
 * Each asset is trimmed of its transparent margin first: a logo padded with
 * whitespace inside its own PNG renders visually smaller than its neighbours
 * however carefully the boxes are laid out.
 *
 *   node scripts/build-brand-assets.mjs
 */
import sharp from "sharp";
import { readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const SRC = "brand-assets";
const OUT = "src/assets/brandAssets.ts";

/* Rendered at ~26mm wide; 600px covers 300dpi print with room to spare. */
const MAX_W = 600;
const MAX_H = 260;

const USE = {
  "Microsoft_Solutions_Partner.png": "microsoftSolutionsPartner",
  "Adobe_Certified_Reseller.png": "adobeCertifiedReseller",
  "Cisco_Partner_Supplied_Reference.png": "ciscoPartner",
  "HP_Logo.png": "hp",
  "Acer_Logo.png": "acer",
  /* The three ISO certification marks, supplied as artwork. They were
     previously drawn as text because the earlier PNGs overflowed their own
     ring; these are clean, so the real marks are used. */
  "ISO_9001_2015.png": "iso9001",
  "ISO_27001_2022.png": "iso27001",
  "ISO_IEC_20000-1_2018.png": "iso20000",
};

/* The ISO marks arrive on an off-white field (#f7f7f7 to #fdfdfd), not on
   white and not on transparency. Trimming cannot remove it — on the 9001
   mark the ring touches the edge, so there is no margin to trim — and left
   alone it prints as a faint grey square behind the badge on an otherwise
   white page.

   So near-white is snapped to pure white. The threshold is deliberately
   high: the palest thing inside any of these marks is the silver ring of
   the 27001 badge at about 190, well clear of 245, and the artwork's own
   whites are already 255. Nothing in the mark itself is altered. */
const WHITE_SNAP = 245;
async function flattenNearWhite(input) {
  const { data, info } = await sharp(input).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  for (let i = 0; i < data.length; i += info.channels) {
    if (data[i] >= WHITE_SNAP && data[i + 1] >= WHITE_SNAP && data[i + 2] >= WHITE_SNAP) {
      data[i] = 255; data[i + 1] = 255; data[i + 2] = 255;
    }
  }
  return sharp(data, { raw: { width: info.width, height: info.height, channels: info.channels } }).png().toBuffer();
}

const entries = [];
for (const file of readdirSync(SRC).filter((f) => f.endsWith(".png")).sort()) {
  const key = USE[file];
  if (!key) continue;
  /* Only the certification marks need it; the partner logos already ship
     on transparency. */
  const source = key.startsWith("iso") ? await flattenNearWhite(join(SRC, file)) : join(SRC, file);
  const img = sharp(source);
  const before = await img.metadata();
  const buf = await img
    .trim({ threshold: 10 })
    .resize({ width: MAX_W, height: MAX_H, fit: "inside", withoutEnlargement: true })
    .png({ compressionLevel: 9, palette: true })
    .toBuffer();
  const after = await sharp(buf).metadata();
  entries.push({ key, file, w: after.width, h: after.height, b64: buf.toString("base64") });
  console.log(`${file}: ${before.width}x${before.height} -> ${after.width}x${after.height}, ${(buf.length / 1024).toFixed(0)} KB`);
}

const body = entries
  .map((e) => `  /** ${e.file} — ${e.w}x${e.h} */\n  ${e.key}: {\n    w: ${e.w},\n    h: ${e.h},\n    src: "data:image/png;base64,${e.b64}",\n  },`)
  .join("\n");

writeFileSync(OUT, `/* GENERATED by scripts/build-brand-assets.mjs — do not edit by hand.
 *
 * The supplied partner artwork, trimmed of its transparent margin and
 * downscaled for print, as embeddable data URIs. Source files live in
 * brand-assets/ alongside the supplier's README, which governs how each may
 * be used. Do not invent designations or alter official badge wording.
 */

export interface BrandAsset {
  w: number;
  h: number;
  src: string;
}

export const BRAND_ASSETS = {
${body}
} as const satisfies Record<string, BrandAsset>;

export type BrandAssetKey = keyof typeof BRAND_ASSETS;
`);
console.log(`\nwrote ${OUT}`);
