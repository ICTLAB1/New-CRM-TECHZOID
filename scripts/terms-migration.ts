/**
 * Write a migration that copies DOMESTIC_TERMS into the two stores a new
 * document actually reads its terms from.
 *
 * WHY THIS EXISTS. termsFor() in src/domain/documents/create.ts looks in
 * three places, in order:
 *
 *   1. the chosen quotation template's own terms, if it has any
 *   2. settings.data->'defaultTerms', the workspace default
 *   3. DOMESTIC_TERMS, the set shipped with the CRM
 *
 * A live workspace has (2) set and often (1), so editing (3) changes what
 * a brand-new workspace would get and nothing about what this one prints.
 * That is not a bug to fix in the code — a company's own saved terms must
 * win over the shipped ones — it just means a change to the supplied set
 * is only half a change until the stored copies are moved too.
 *
 * WHEN THE CLAUSES CHANGE AGAIN, run this to produce the NEXT migration:
 *
 *   npx tsx scripts/terms-migration.ts 054
 *
 * A number that already exists is refused. Never edit a migration that
 * has been applied: the ledger will not run it a second time, so the
 * edit reaches no database and the only sign of it is a test failing.
 */
import { existsSync, writeFileSync } from "node:fs";
import { DOMESTIC_TERMS } from "../src/domain/documents/terms";

const n = process.argv[2];
if (!n || !/^\d{3}$/.test(n)) {
  console.error("Give the migration number, three digits: npx tsx scripts/terms-migration.ts 054");
  process.exit(1);
}
const path = `supabase/${n}_supplied_terms_everywhere.sql`;
if (existsSync(path) && process.argv[3] !== "--overwrite") {
  console.error(`${path} already exists. Pick the next free number, or pass --overwrite if it has never been deployed.`);
  process.exit(1);
}

const json = JSON.stringify(DOMESTIC_TERMS, null, 2);
const kept = `Before${n}`;

const sql = `/*
 * Put the company's own terms where new documents actually read them.
 *
 * WHY A CODE CHANGE IS NOT ENOUGH: DOMESTIC_TERMS is the LAST of three
 * places a new quotation looks. termsFor() in create.ts reads, in order,
 * the chosen quotation template's own terms, then
 * settings.data->'defaultTerms', then the set shipped with the CRM. A
 * live workspace has the second set and often the first, so replacing
 * the clauses in the code changed what a brand-new workspace would get
 * and nothing at all about what this one prints — which is what a
 * quotation raised afterwards showed: the clauses saved in Settings,
 * exactly as before.
 *
 * WHAT IT DOES. Both stores are set to the supplied clauses, carrying
 * {{company}} where the company names itself — the same shape the code's
 * set has, because create.ts fills that in per document and a stored
 * name would be the wrong company's on the other company's quotations.
 *
 * NOTHING IS DESTROYED. The previous value of each is kept beside it, as
 * defaultTerms${kept} and, on each template, terms${kept}. Restoring is a
 * copy back, and the old text is there to read in the meantime.
 *
 * WHAT IT DOES NOT TOUCH: documents that already exist. A quotation
 * carries the terms it was saved with, and one already sent to a customer
 * must keep the terms that customer was sent — rewriting those would
 * alter the text of an offer after it was made. A draft is brought up to
 * date by opening it and applying the standard set on the Terms tab.
 *
 * Generated by scripts/terms-migration.ts. Idempotent: a second run
 * matches nothing.
 */

/* ── 1. the workspace default ──────────────────────────────────────── */
with supplied as (select $json$${json}$json$::jsonb as t)
update public.settings s
   set data = jsonb_set(
         case when s.data ? 'defaultTerms'
              then jsonb_set(s.data, '{defaultTerms${kept}}', s.data->'defaultTerms')
              else s.data end,
         '{defaultTerms}', (select t from supplied)),
       updated_at = now()
 where s.data->'defaultTerms' is distinct from (select t from supplied);

/* ── 2. every quotation template that carries its own terms ──────────
   Rebuilt WITH ORDINALITY: jsonb_agg over jsonb_array_elements is free to
   return the templates in any order, and the first template is the one a
   new quotation is raised from. */
with supplied as (select $json$${json}$json$::jsonb as t)
update public.settings s
   set data = jsonb_set(s.data, '{quoteTemplates}', (
         select jsonb_agg(
           case when jsonb_typeof(e->'terms') = 'array'
                     and e->'terms' is distinct from '[]'::jsonb
                     and e->'terms' is distinct from (select t from supplied)
                then jsonb_set(jsonb_set(e, '{terms${kept}}', e->'terms'),
                               '{terms}', (select t from supplied))
                else e end
           order by ord)
         from jsonb_array_elements(s.data->'quoteTemplates') with ordinality as a(e, ord)
       )),
       updated_at = now()
 /* CASE, not AND. Postgres may evaluate the parts of an AND in any order,
    so a row whose quoteTemplates is not an array — hand-edited settings,
    an older shape — made jsonb_array_elements throw "cannot get array
    length of a scalar" and would have taken the whole deploy down with
    it. CASE is the one construct that guarantees the type is checked
    first. Found by running this against a throwaway Postgres carrying
    exactly that row. */
 where case when jsonb_typeof(s.data->'quoteTemplates') = 'array'
            then exists (
              select 1 from jsonb_array_elements(s.data->'quoteTemplates') e
               where jsonb_typeof(e->'terms') = 'array'
                 and e->'terms' is distinct from '[]'::jsonb
                 and e->'terms' is distinct from (select t from supplied))
            else false end;
`;

writeFileSync(path, sql);
console.log(`wrote ${path} with ${DOMESTIC_TERMS.length} clauses`);
