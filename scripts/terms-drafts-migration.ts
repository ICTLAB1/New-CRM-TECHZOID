/**
 * Write a migration that brings DRAFT quotations and proformas onto the
 * supplied terms.
 *
 * A document stores the terms it was created with, which is why changing
 * the default does not reach the ones already saved. For a draft that is
 * usually unwanted: nobody has seen it, and it is about to go out with
 * last year's clauses on it.
 *
 * WHAT IT WILL NOT TOUCH, and these are the lines that matter:
 *
 *   - anything that is not status Draft. A quotation that has been sent
 *     is an offer that was made, in the words it was made in. Rewriting
 *     its terms changes what the customer was told after the fact.
 *   - an export document. suggestTermsSet gives a customer outside India
 *     the international set — Incoterms, zero-rated supply, arbitration —
 *     and the domestic set on an export is wrong in law, not in wording.
 *   - purchase orders and tax invoices, which have sets of their own that
 *     face the other way.
 *
 * Each document keeps its previous terms under termsBefore<nnn>, so this
 * is reversible per document and the old wording stays readable.
 *
 *   npx tsx scripts/terms-drafts-migration.ts 054
 */
import { existsSync, writeFileSync } from "node:fs";
import { DOMESTIC_TERMS, SELLER_TOKEN } from "../src/domain/documents/terms";

const n = process.argv[2];
if (!n || !/^\d{3}$/.test(n)) {
  console.error("Give the migration number, three digits: npx tsx scripts/terms-drafts-migration.ts 054");
  process.exit(1);
}
const path = `supabase/${n}_supplied_terms_on_drafts.sql`;
if (existsSync(path) && process.argv[3] !== "--overwrite") {
  console.error(`${path} already exists. Pick the next free number, or pass --overwrite if it has never been deployed.`);
  process.exit(1);
}

const json = JSON.stringify(DOMESTIC_TERMS, null, 2);
const kept = `termsBefore${n}`;

/** One table's worth. quotes and proformas have the same shape and the
 *  same default terms; they differ only in which statuses exist. */
const forTable = (table: string) => `
/* ── ${table} ─────────────────────────────────────────────────────── */
with supplied as (select $json$${json}$json$::jsonb as t)
update public.${table} d
   set data = jsonb_set(
         jsonb_set(d.data, '{${kept}}', coalesce(d.data->'terms', '[]'::jsonb)),
         '{terms}',
         (select jsonb_agg(
            to_jsonb(replace(e #>> '{}', '${SELLER_TOKEN}', public.seller_name_${n}(d.company_id)))
            order by ord)
          from supplied, jsonb_array_elements(supplied.t) with ordinality as a(e, ord))),
       updated_at = now()
 where d.data->>'status' = 'Draft'
   /* Domestic only. Empty country means the workspace default, which is
      India — the same rule suggestTermsSet applies. */
   and coalesce(nullif(trim(d.data->>'billCountry'), ''), 'India') = 'India'
   /* Already carrying them: nothing to do, and no second copy of the
      previous terms to overwrite the real one. */
   and d.data->'terms' is distinct from (
     select jsonb_agg(
       to_jsonb(replace(e #>> '{}', '${SELLER_TOKEN}', public.seller_name_${n}(d.company_id))) order by ord)
     from supplied, jsonb_array_elements(supplied.t) with ordinality as a(e, ord));
`;

const sql = `/*
 * Bring DRAFT quotations and proformas onto the supplied terms.
 *
 * Migration ${Number(n) - 1} put the clauses where NEW documents read them. A
 * document already saved keeps the terms it was created with — which is
 * right for one that has been sent, and wrong for a draft nobody has
 * seen that is about to go out with last year's clauses on it.
 *
 * WHAT IT WILL NOT TOUCH:
 *
 *   - anything that is not status Draft. A quotation that has been sent
 *     is an offer that was made, in the words it was made in; rewriting
 *     its terms changes what the customer was told after the fact. Sent,
 *     Accepted, Rejected, Expired and Paid are all left exactly as they
 *     are.
 *   - an export document. A customer outside India gets the
 *     international set — Incoterms, zero-rated supply, arbitration —
 *     and the domestic set on an export is wrong in law, not in wording.
 *   - purchase_orders and invoices, which carry sets of their own that
 *     face the other way: a purchase order's terms are what WE require
 *     of a supplier.
 *
 * THE COMPANY'S NAME IS FILLED IN PER DOCUMENT, from the settings row of
 * the company that document belongs to — the stored sets carry
 * ${SELLER_TOKEN} and a saved document does not, because a document is
 * a record of what it said. A document whose company has no name set
 * falls back to "the Company", exactly as forCompany does in the app,
 * rather than borrowing the other company's name.
 *
 * Each document keeps its previous terms under ${kept}, so this is
 * reversible per document and the old wording stays readable.
 *
 * Generated by scripts/terms-drafts-migration.ts. Idempotent: a second
 * run matches nothing.
 */

/* The seller's name as forCompany() resolves it: the company's own name,
   or the neutral phrase when it has none — never the other company's.
   A function rather than a join, because a join that found no settings
   row would drop the document from the update instead of naming it
   neutrally, and the coalesce has to wrap the whole subquery: with no
   settings row at all it returns no row, not an empty string. */
create or replace function public.seller_name_${n}(c uuid)
returns text language sql stable as $fn$
  select coalesce(
    (select nullif(trim(s.data->'company'->>'name'), '')
       from public.settings s where s.company_id = c limit 1),
    'the Company')
$fn$;
${forTable("quotes")}${forTable("proformas")}
/* Printed into the deploy log, so the change has a number against it.
   It counts the documents carrying a saved copy of their previous terms,
   which on this one run is the documents this migration touched.
   NOTICE, never EXCEPTION: a raise that aborts would fail the deploy
   over a line of reporting. */
do $$
declare
  q integer;
  p integer;
begin
  select count(*) into q from public.quotes where data ? '${kept}';
  select count(*) into p from public.proformas where data ? '${kept}';
  raise notice 'supplied terms applied to % draft quotation(s) and % draft proforma(s)', q, p;
end $$;

drop function if exists public.seller_name_${n}(uuid);
`;

writeFileSync(path, sql);
console.log(`wrote ${path} with ${DOMESTIC_TERMS.length} clauses`);
