/**
 * Write a migration that puts the proforma sets on DRAFT proformas.
 *
 * Migration 054 brought draft proformas onto the supplied terms — but
 * onto the QUOTATION set, because at the time that was the only set a
 * proforma had. That is the fault this corrects: a proforma invoice
 * reading "Quotation Validity: This quotation is valid for 7 days".
 *
 * Domestic and export are separate statements, because they are
 * different documents in law: a proforma on a customer outside India
 * needs Incoterms, the importer of record and arbitration, and 054
 * skipped those entirely.
 *
 * KEEPS WHAT WAS THERE FIRST, not what 054 left. Where 054 already saved
 * a document's original terms under termsBefore054 that copy is left
 * alone — saving the quotation set over it would replace the only record
 * of what the document actually said. Where there is no such copy (an
 * export proforma, which 054 passed over), the current terms are the
 * original and are saved under termsBefore055.
 *
 *   npx tsx scripts/proforma-terms-migration.ts 055
 */
import { existsSync, writeFileSync } from "node:fs";
import { PROFORMA_EXPORT_TERMS, PROFORMA_TERMS, SELLER_TOKEN } from "../src/domain/documents/terms";

const n = process.argv[2];
if (!n || !/^\d{3}$/.test(n)) {
  console.error("Give the migration number, three digits: npx tsx scripts/proforma-terms-migration.ts 055");
  process.exit(1);
}
const path = `supabase/${n}_proforma_terms_on_drafts.sql`;
if (existsSync(path) && process.argv[3] !== "--overwrite") {
  console.error(`${path} already exists. Pick the next free number, or pass --overwrite if it has never been deployed.`);
  process.exit(1);
}

const kept = `termsBefore${n}`;

/** One statement: a set, and the countries it belongs on. */
const forSet = (terms: readonly string[], where: string, what: string) => `
/* ── ${what} ─────────────────────────────────────────── */
with supplied as (select $json$${JSON.stringify(terms, null, 2)}$json$::jsonb as t)
update public.proformas d
   set data = jsonb_set(
         /* Only when 054 did not already save the original. */
         case when d.data ? 'termsBefore054'
              then d.data
              else jsonb_set(d.data, '{${kept}}', coalesce(d.data->'terms', '[]'::jsonb)) end,
         '{terms}',
         (select jsonb_agg(
            to_jsonb(replace(e #>> '{}', '${SELLER_TOKEN}', public.seller_name_${n}(d.company_id)))
            order by ord)
          from supplied, jsonb_array_elements(supplied.t) with ordinality as a(e, ord))),
       updated_at = now()
 where d.data->>'status' = 'Draft'
   and ${where}
   and d.data->'terms' is distinct from (
     select jsonb_agg(
       to_jsonb(replace(e #>> '{}', '${SELLER_TOKEN}', public.seller_name_${n}(d.company_id))) order by ord)
     from supplied, jsonb_array_elements(supplied.t) with ordinality as a(e, ord));
`;

const DOMESTIC = "coalesce(nullif(trim(d.data->>'billCountry'), ''), 'India') = 'India'";
const EXPORT = "coalesce(nullif(trim(d.data->>'billCountry'), ''), 'India') <> 'India'";

const sql = `/*
 * A proforma invoice stops calling itself a quotation.
 *
 * Migration 054 brought draft proformas onto the supplied terms, but
 * onto the QUOTATION set — the only set a proforma had at the time. So
 * a proforma invoice went out reading "Quotation Validity: This
 * quotation is valid for 7 days", "unless specifically included in the
 * quotation", and asking for acceptance of an offer it was no longer
 * making.
 *
 * The proforma sets are the company's own clauses with the words that
 * name the document changed, the two clauses that only make sense on an
 * offer rewritten, and one clause added that a proforma has to carry:
 * it is not a tax invoice and no input tax credit can be claimed
 * against it.
 *
 * DOMESTIC AND EXPORT ARE SEPARATE, because they are different
 * documents in law — a proforma on a customer outside India needs
 * Incoterms, the importer of record and arbitration. 054 skipped those
 * entirely; this reaches them.
 *
 * DRAFTS ONLY, as 054 was. A proforma that has been sent is a demand
 * that was made, in the words it was made in.
 *
 * KEEPS WHAT WAS THERE FIRST. Where 054 already saved a document's
 * original terms under termsBefore054, that copy is left alone: saving
 * the quotation set over it would replace the only record of what the
 * document actually said. Where there is none — an export proforma,
 * which 054 passed over — the current terms are the original and are
 * saved under ${kept}.
 *
 * Generated by scripts/proforma-terms-migration.ts. Idempotent: a
 * second run matches nothing.
 */

create or replace function public.seller_name_${n}(c uuid)
returns text language sql stable as $fn$
  select coalesce(
    (select nullif(trim(s.data->'company'->>'name'), '')
       from public.settings s where s.company_id = c limit 1),
    'the Company')
$fn$;
${forSet(PROFORMA_TERMS, DOMESTIC, "domestic proformas")}${forSet(PROFORMA_EXPORT_TERMS, EXPORT, "export proformas")}
do $$
declare
  d integer;
begin
  select count(*) into d from public.proformas
   where data->>'status' = 'Draft'
     and data->'terms' @> '["Validity: This proforma invoice is valid for 7 days from the date of issue, unless otherwise specified. Prices and product availability are subject to change thereafter."]'::jsonb;
  raise notice 'proforma terms now on % domestic draft proforma(s)', d;
end $$;

drop function if exists public.seller_name_${n}(uuid);
`;

writeFileSync(path, sql);
console.log(`wrote ${path}: ${PROFORMA_TERMS.length} domestic, ${PROFORMA_EXPORT_TERMS.length} export clauses`);
