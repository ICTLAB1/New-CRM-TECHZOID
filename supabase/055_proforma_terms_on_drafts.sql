/*
 * A proforma invoice stops calling itself a quotation.
 *
 * Migration 054 brought draft proformas onto the supplied terms, but
 * onto the QUOTATION set — the only set a proforma had at the time. So
 * a proforma invoice went out reading "Quotation Validity: This
 * quotation is valid for 7 days", "unless specifically included in the
 * quotation", and asking for acceptance of an offer it was no longer
 * making.
 *
 * The proforma sets are the company's own clauses with the words that
 * name the document changed, the two clauses that only make sense on an
 * offer rewritten, and one clause added that a proforma has to carry:
 * it is not a tax invoice and no input tax credit can be claimed
 * against it.
 *
 * DOMESTIC AND EXPORT ARE SEPARATE, because they are different
 * documents in law — a proforma on a customer outside India needs
 * Incoterms, the importer of record and arbitration. 054 skipped those
 * entirely; this reaches them.
 *
 * DRAFTS ONLY, as 054 was. A proforma that has been sent is a demand
 * that was made, in the words it was made in.
 *
 * KEEPS WHAT WAS THERE FIRST. Where 054 already saved a document's
 * original terms under termsBefore054, that copy is left alone: saving
 * the quotation set over it would replace the only record of what the
 * document actually said. Where there is none — an export proforma,
 * which 054 passed over — the current terms are the original and are
 * saved under termsBefore055.
 *
 * Generated by scripts/proforma-terms-migration.ts. Idempotent: a
 * second run matches nothing.
 */

create or replace function public.seller_name_055(c uuid)
returns text language sql stable as $fn$
  select coalesce(
    (select nullif(trim(s.data->'company'->>'name'), '')
       from public.settings s where s.company_id = c limit 1),
    'the Company')
$fn$;

